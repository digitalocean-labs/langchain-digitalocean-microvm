"""In-process local transport backed by a real local subprocess.

No MicroVM, network, or SSH involved: commands run for real via `bash -lc`
against a directory on local disk, so this genuinely exercises the shell/
python3 scripts deepagents.backends.sandbox.BaseSandbox generates. State is
keyed off the `host` string passed to connect() (see `_root_for_host`) so a
fresh LocalTransport that connects() with the same host sees the same
filesystem — this is how provider.py simulates pause/resume without a real
backend.

Absolute-path isolation
------------------------
On a real transport (ssh/http), an absolute path like "/notes.md" is
naturally scoped to that one MicroVM -- it IS the whole machine. LocalTransport
instead runs a real subprocess against *this* machine, so without extra care
an absolute path would resolve against the real host filesystem instead of
the sandbox root: `put_file`/`get_file` (used by upload_files/download_files,
and therefore by BaseSandbox.write()) already handle this correctly via
`_resolve()`, but a raw shell command passed to `run()` (whether typed
directly, as in a smoke test, or generated by BaseSandbox's read/ls/grep/glob/
edit/delete helpers) does not -- `cat /notes.md`, or the python3 scripts those
helpers emit, would read/write/delete real files on the host running the
tests. This is not just a correctness gap: it defeats the entire point of a
"local", zero-risk, offline transport.

`run()` closes this gap for every subprocess it spawns via two additive,
best-effort mechanisms (see `_ensure_shim_dir()`):

- `PYTHONPATH` points at a `sitecustomize.py` that monkeypatches the handful
  of `os`/builtins path-taking functions BaseSandbox's generated `python3 -c`
  scripts use (`os.stat`, `open`, `os.scandir`, `os.chdir`, `os.path.isdir`,
  `os.path.realpath`, `os.makedirs`, `os.remove`) so an absolute path is
  transparently rewritten under this LocalTransport's sandbox root before the
  real call happens.
- `BASH_ENV` sources a small script defining shell functions for the plain
  (non-python3) commands BaseSandbox emits directly (`test`, `rm`) plus a
  few common ones useful for ad-hoc `execute()` calls (`cat`, `ls`, `mkdir`,
  `touch`, `mv`, `cp`, `head`, `tail`, `stat`, `wc`, `ln`), each rewriting any
  absolute argument the same way. Any BASH_ENV the caller already had set
  (e.g. a test's own shell-quirk fix) is still sourced afterwards, chained.

This is deliberately not a real chroot (unprivileged processes can't create
one) -- it is a best-effort rewrite of the specific path-taking calls this
package's generated commands are known to make, not a guarantee that *every*
possible shell command is contained. Known gap: `grep`'s raw-shell route
(`_build_grep_cmd` without a `/`-containing glob) is not rewritten, since its
last positional argument can't be distinguished from an arbitrary
`-e PATTERN` value without a real argv parse; the `/`-containing-glob route
(a separate, python3-based template) is covered like everything else. Shell
redirects to absolute paths are not rewritten either, which is why
`supports_capture_offload` is False here (see MicroVMSandbox).
"""

from __future__ import annotations

import os
import re
import subprocess
import tempfile
from functools import lru_cache
from pathlib import Path

from langchain_digitalocean_microvm.transport.base import (
    SandboxTransport,
    TransportCredentials,
    TransportExecResult,
)
from langchain_digitalocean_microvm.transport.errors import (
    TransportError,
    TransportFileNotFoundError,
    TransportIsADirectoryError,
)

_ROOT_ENV_VAR = "MICROVM_LOCAL_ROOT"
_USER_BASH_ENV_VAR = "MICROVM_LOCAL_USER_BASH_ENV"

_SITECUSTOMIZE_SOURCE = f'''"""Auto-imported by every python3 -c invocation LocalTransport spawns.

See langchain_digitalocean_microvm.transport.local's module docstring ("Absolute-path
isolation") for why this exists. Only active when {_ROOT_ENV_VAR} is set,
which LocalTransport.run() always does for its own subprocesses -- a plain
`python3` invocation outside that context is completely unaffected.
"""
import os
import builtins

_ROOT = os.environ.get("{_ROOT_ENV_VAR}")


def _redirect(path):
    """Rewrite an absolute path under _ROOT, unless it is already there."""
    if _ROOT and isinstance(path, str) and path.startswith("/") and not path.startswith(_ROOT):
        return os.path.join(_ROOT, path[1:])
    return path


if _ROOT:
    _real_stat = os.stat
    os.stat = lambda path, *a, **kw: _real_stat(_redirect(path), *a, **kw)

    _real_open = builtins.open
    builtins.open = lambda file, *a, **kw: _real_open(
        _redirect(file) if isinstance(file, str) else file, *a, **kw
    )

    _real_scandir = os.scandir
    os.scandir = lambda path=".": _real_scandir(_redirect(path))

    _real_chdir = os.chdir
    os.chdir = lambda path: _real_chdir(_redirect(path))

    _real_isdir = os.path.isdir
    os.path.isdir = lambda path: _real_isdir(_redirect(path))

    _real_realpath = os.path.realpath
    os.path.realpath = lambda path, *a, **kw: _real_realpath(_redirect(path), *a, **kw)

    _real_makedirs = os.makedirs
    os.makedirs = lambda name, *a, **kw: _real_makedirs(_redirect(name), *a, **kw)

    _real_remove = os.remove
    os.remove = lambda path, *a, **kw: _real_remove(_redirect(path), *a, **kw)
'''

_BASH_SHIM_SOURCE = f'''# Auto-sourced (via BASH_ENV) by every command LocalTransport.run() spawns.
# See langchain_digitalocean_microvm.transport.local's module docstring for why.
if [ -n "${{{_ROOT_ENV_VAR}:-}}" ]; then
    _microvm_local_redirect() {{
        case "$1" in
            "${_ROOT_ENV_VAR}"/*) printf '%s' "$1" ;;
            /*) printf '%s' "${_ROOT_ENV_VAR}$1" ;;
            *) printf '%s' "$1" ;;
        esac
    }}

    _microvm_local_wrap() {{
        eval "
$1() {{
    local args=() a
    for a in \\"\\$@\\"; do
        args+=(\\"\\$(_microvm_local_redirect \\"\\$a\\")\\")
    done
    command $1 \\"\\${{args[@]}}\\"
}}
"
    }}

    for _microvm_local_cmd in cat rm mkdir touch mv cp head tail stat wc ln test; do
        _microvm_local_wrap "$_microvm_local_cmd"
    done
    unset -f _microvm_local_wrap
    unset _microvm_local_cmd
fi

if [ -n "${{{_USER_BASH_ENV_VAR}:-}}" ]; then
    # shellcheck disable=SC1090
    . "${_USER_BASH_ENV_VAR}"
fi
'''


@lru_cache(maxsize=1)
def _ensure_shim_dir() -> Path:
    """Write the sitecustomize.py / bash shim once per process, return their directory."""
    shim_dir = Path(tempfile.gettempdir()) / "microvm_sandbox_local_shim"
    shim_dir.mkdir(parents=True, exist_ok=True)
    (shim_dir / "sitecustomize.py").write_text(_SITECUSTOMIZE_SOURCE)
    (shim_dir / "bash_shim.sh").write_text(_BASH_SHIM_SOURCE)
    return shim_dir


def _root_for_host(host: str) -> Path:
    safe = re.sub(r"[^A-Za-z0-9_.-]", "_", host)
    root = Path(tempfile.gettempdir()) / "microvm_sandbox_local" / safe
    root.mkdir(parents=True, exist_ok=True)
    return root


class LocalTransport(SandboxTransport):
    """Runs commands as a real local subprocess against a directory on disk."""

    # Shell redirects (`> /large_tool_results/x`) cannot be rewritten into the
    # sandbox root, so deepagents' capture-at-source execute wrapper would fail
    # (or write to the host's real /). MicroVMSandbox turns the offload off for
    # this transport; large outputs then go through deepagents' generic eviction.
    supports_capture_offload = False

    def __init__(self) -> None:
        self._root: Path | None = None
        self._connected = False

    def connect(
        self,
        *,
        host: str,
        port: int,
        credentials: TransportCredentials,
        timeout: float | None = None,
    ) -> None:
        self._root = _root_for_host(host)
        self._connected = True

    def close(self) -> None:
        self._connected = False

    @property
    def is_connected(self) -> bool:
        return self._connected

    def _subprocess_env(self) -> dict[str, str]:
        """Base environment plus the absolute-path-isolation hooks (see module docstring)."""
        assert self._root is not None
        shim_dir = _ensure_shim_dir()
        env = dict(os.environ)
        existing_pythonpath = env.get("PYTHONPATH")
        env["PYTHONPATH"] = (
            f"{shim_dir}{os.pathsep}{existing_pythonpath}" if existing_pythonpath else str(shim_dir)
        )
        env[_USER_BASH_ENV_VAR] = env.get("BASH_ENV", "")
        env["BASH_ENV"] = str(shim_dir / "bash_shim.sh")
        # Fully resolved (symlinks included, e.g. macOS's /var -> /private/var):
        # os.path.realpath() inside the generated python3 scripts returns this
        # same canonical form, so the "already under root" double-redirect
        # guard in sitecustomize.py's _redirect() only works if the env var
        # it compares against is resolved the same way.
        env[_ROOT_ENV_VAR] = str(self._root.resolve())
        return env

    def run(self, command: str, *, timeout: float | None = None) -> TransportExecResult:
        try:
            result = subprocess.run(
                ["bash", "-lc", command],
                cwd=self._root,
                capture_output=True,
                text=True,
                timeout=timeout,
                env=self._subprocess_env(),
            )
        except subprocess.TimeoutExpired as exc:
            return TransportExecResult(
                stdout=_text(exc.stdout),  # TimeoutExpired carries bytes even with text=True
                stderr=_text(exc.stderr),
                exit_code=None,
            )
        return TransportExecResult(
            stdout=result.stdout,
            stderr=result.stderr,
            exit_code=result.returncode,
        )

    def _resolve(self, path: str) -> Path:
        assert self._root is not None
        return self._root / path.lstrip("/")

    def put_file(self, path: str, content: bytes) -> None:
        target = self._resolve(path)
        if target.is_dir():
            raise TransportIsADirectoryError(path)
        try:
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_bytes(content)
        except OSError as exc:
            raise TransportError(f"Failed to write {path!r}: {exc}") from exc

    def get_file(self, path: str) -> bytes:
        target = self._resolve(path)
        if not target.exists():
            raise TransportFileNotFoundError(path)
        if target.is_dir():
            raise TransportIsADirectoryError(path)
        return target.read_bytes()


# Public alias: agent_host.local.LocalDevServerHost points the subagent's
# SUBAGENT_WORKDIR at a directory of this kind (its own key per host).
root_for_host = _root_for_host


def _text(value: str | bytes | None) -> str:
    return value.decode(errors="replace") if isinstance(value, bytes) else (value or "")
